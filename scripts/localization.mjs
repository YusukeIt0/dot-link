import { readFile, writeFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const read = async path => JSON.parse(await readFile(new URL(path, root), 'utf8'));
export async function checkLocalization({ write = false } = {}) {
  const metadata = await read('localization/locales.json');
  const locales = Object.keys(metadata);
  const files = (await readdir(new URL('localization/', root))).filter(name => name.endsWith('.json') && name !== 'locales.json').sort();
  if (JSON.stringify(files) !== JSON.stringify(locales.map(locale => `${locale}.json`).sort())) throw Error('Catalog files and registered locales differ');
  const catalogs = Object.fromEntries(await Promise.all(locales.map(async locale => [locale, await read(`localization/${locale}.json`)])));
  validateCatalogs(metadata, catalogs);
  const keys = Object.keys(catalogs.en);
  const generated = '// Generated by node scripts/localization.mjs --write. Edit localization/ resources.\n'
    + locales.map(locale => `import ${locale} from '../localization/${locale}.json' with { type: 'json' };`).join('\n')
    + `\nimport localeMetadata from '../localization/locales.json' with { type: 'json' };\nexport { localeMetadata };\nexport const catalogs = { ${locales.join(', ')} };\nexport type Language = keyof typeof catalogs;\nexport type MessageKey = keyof typeof en;\n`;
  const target = new URL('src/localization-catalogs.ts', root);
  if (write) await writeFile(target, generated);
  else if (await readFile(target, 'utf8').catch(() => '') !== generated) throw Error('Localization imports are stale; run node scripts/localization.mjs --write');
  const html = await readFile(new URL('index.html', root), 'utf8');
  for (const [, key] of html.matchAll(/data-i18n(?:-aria-label)?="([^"]+)"/g)) if (!Object.hasOwn(catalogs.en, key)) throw Error(`Unknown HTML message: ${key}`);
  if (/data-en=/.test(html)) throw Error('Legacy HTML translation outside catalogs');
  return { locales, messages: keys.length };
}

export function validateCatalogs(metadata, catalogs) {
  const locales = Object.keys(metadata);
  if (!locales.includes('en')) throw Error('English fallback is required');
  if (JSON.stringify(Object.keys(catalogs).sort()) !== JSON.stringify([...locales].sort())) throw Error('Catalogs and registered locales differ');
  const orders = new Set();
  for (const [locale, entry] of Object.entries(metadata)) {
    if (!/^[a-z]{2,3}$/.test(locale) || !entry.name?.trim() || !entry.speechLocale?.startsWith(locale + '-') || !entry.dateLocale?.startsWith(locale + '_') || !Number.isInteger(entry.order) || orders.has(entry.order)) throw Error(`Invalid locale metadata: ${locale}`);
    orders.add(entry.order);
  }
  const keys = Object.keys(catalogs.en).sort();
  const parameters = value => [...value.matchAll(/\{([a-zA-Z][a-zA-Z0-9_]*)\}/g)].map(match => match[1]).sort().join(',');
  for (const [locale, catalog] of Object.entries(catalogs)) {
    if (JSON.stringify(Object.keys(catalog).sort()) !== JSON.stringify(keys)) throw Error(`Missing/extra translation keys: ${locale}`);
    for (const [key, value] of Object.entries(catalog)) {
      if (!/^(common|even|mac|setup)\.[a-zA-Z0-9_.-]+$/.test(key) || typeof value !== 'string' || !value.trim()) throw Error(`Invalid translation: ${locale}:${key}`);
      if (parameters(value) !== parameters(catalogs.en[key])) throw Error(`Placeholder mismatch: ${locale}:${key}`);
      if (/[{}]/.test(value.replace(/\{([a-zA-Z][a-zA-Z0-9_]*)\}/g, ''))) throw Error(`Invalid placeholder syntax: ${locale}:${key}`);
    }
  }
}
if (process.argv[1] === fileURLToPath(import.meta.url)) console.log(await checkLocalization({ write: process.argv.includes('--write') }));
